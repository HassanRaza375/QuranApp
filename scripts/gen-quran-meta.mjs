// Generates app/data/quranMeta.generated.ts: where each of the 30 juz and 604 mushaf pages starts (surah and ayah),
// and the 114 surah rows for the listing (names, place, ayah count) WITHOUT the audio map.
//
//   node scripts/gen-quran-meta.mjs
//
// Source: GET https://api.alquran.cloud/v1/meta (an API the app already uses), `juzs.references`, `pages.references`.
// Surah rows come from the legacy data file (legacy/app/assets/data/surah.json) so they are the same words the rest of the app
// shows. The script FAILS (writes nothing) when the upstream disagrees with the legacy data, so a changed upstream is
// noticed instead of silently followed. It stores numbers and the legacy names only: no Qur'an text.
// Never hand-edit the generated file; re-run this script.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const legacy = JSON.parse(fs.readFileSync(path.resolve(here, "../legacy/app/assets/data/surah.json"), "utf8"));
const BASE = process.env.QURAN_API_BASE2 || "https://api.alquran.cloud/v1";

const res = await fetch(`${BASE}/meta`);
if (!res.ok) throw new Error(`meta: HTTP ${res.status}`);
const { data } = await res.json();

const fail = (m) => {
  throw new Error(`meta check failed: ${m}`);
};

if (legacy.length !== 114) fail(`legacy data has ${legacy.length} surahs`);
const counts = legacy.map((s) => s.totalAyah);
if (counts.reduce((a, b) => a + b, 0) !== 6236) fail("legacy ayah counts do not add up to 6236");

// The surah list in the response must equal the legacy list (number, ayah count, place).
const upstreamSurahs = data.surahs.references;
if (upstreamSurahs.length !== 114) fail(`${upstreamSurahs.length} surahs upstream`);
upstreamSurahs.forEach((s, i) => {
  const l = legacy[i];
  if (s.number !== l.surahNo || s.numberOfAyahs !== l.totalAyah) fail(`surah ${i + 1} differs from the legacy data`);
  const place = s.revelationType === "Meccan" ? "Mecca" : s.revelationType === "Medinan" ? "Madina" : null;
  if (place !== l.revelationPlace) fail(`surah ${i + 1}: place ${s.revelationType} vs ${l.revelationPlace}`);
});

function refs(list, count, label) {
  if (list.length !== count) fail(`${label}: ${list.length} entries, expected ${count}`);
  let prev = 0;
  return list.map((r, i) => {
    const s = r.surah;
    const a = r.ayah;
    if (!Number.isInteger(s) || !Number.isInteger(a) || s < 1 || s > 114 || a < 1 || a > counts[s - 1]) fail(`${label} ${i + 1}: ${s}:${a} is not an ayah`);
    const abs = counts.slice(0, s - 1).reduce((x, y) => x + y, 0) + a;
    if (abs <= prev) fail(`${label} ${i + 1}: not increasing`);
    prev = abs;
    return [s, a];
  });
}
const juz = refs(data.juzs.references, 30, "juz");
const pages = refs(data.pages.references, 604, "page");
if (juz[0].join(":") !== "1:1" || pages[0].join(":") !== "1:1") fail("juz 1 and page 1 must start at 1:1");

const rows = legacy.map((s) => ({
  n: s.surahNo,
  name: s.surahName,
  ar: s.surahNameArabic,
  arLong: s.surahNameArabicLong,
  en: s.surahNameTranslation,
  place: s.revelationPlace,
  ayahs: s.totalAyah,
}));

const out = `// GENERATED by scripts/gen-quran-meta.mjs. Do not edit by hand; re-run the script.
// Source: api.alquran.cloud /v1/meta (juz and page starts) and the legacy surah.json (names, place, ayah counts).
// JUZ_STARTS[n - 1] and PAGE_STARTS[n - 1] are [surah, ayah] where juz n or page n begins. Numbers and names only.
export interface SurahRow {
  n: number;
  name: string;
  ar: string;
  arLong: string;
  en: string;
  place: "Mecca" | "Madina";
  ayahs: number;
}

export const SURAH_ROWS: SurahRow[] = ${JSON.stringify(rows, null, 1).replace(/\n\s+/g, " ").replace(/\[ \{/, "[\n  {").replace(/\}, \{/g, "},\n  {").replace(/\} \]/, "},\n]")};

export const JUZ_STARTS: [number, number][] = ${JSON.stringify(juz)};

export const PAGE_STARTS: [number, number][] = ${JSON.stringify(pages)};
`;
fs.writeFileSync(path.resolve(here, "../app/data/quranMeta.generated.ts"), out);
console.log(`wrote app/data/quranMeta.generated.ts (${juz.length} juz, ${pages.length} pages, ${rows.length} surahs, ${(out.length / 1024).toFixed(1)} KiB)`);
