// Generates app/data/ayahLengths.generated.ts: the length (in characters) of every ayah's Arabic text, per surah.
// Used by the Home "Ayah of the day" to pick from "all ayahs under a length cap" without fetching 6,236 verses,
// and for the Qur'an's per-surah ayah counts. It holds numbers only, no Qur'an text.
//
//   node scripts/gen-ayah-lengths.mjs
//
// Source: the same upstream the app reads (quranapi.pages.dev, field `arabic1`). The script fails if any surah's
// ayah count differs from the legacy data file (legacy/app/assets/data/surah.json), so a changed upstream is noticed.
// Never hand-edit the generated file; re-run this script.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const legacy = JSON.parse(fs.readFileSync(path.resolve(here, "../legacy/app/assets/data/surah.json"), "utf8"));
const BASE = process.env.QURAN_API_BASE || "https://quranapi.pages.dev/api";

const lengths = [];
for (let n = 1; n <= 114; n++) {
  const res = await fetch(`${BASE}/${n}.json`);
  if (!res.ok) throw new Error(`surah ${n}: HTTP ${res.status}`);
  const j = await res.json();
  if (!Array.isArray(j.arabic1) || j.arabic1.length !== legacy[n - 1].totalAyah) {
    throw new Error(`surah ${n}: ${j.arabic1?.length} ayahs from the API, ${legacy[n - 1].totalAyah} in the legacy data`);
  }
  lengths.push(j.arabic1.map((t) => t.length));
}
const total = lengths.reduce((a, s) => a + s.length, 0);
if (total !== 6236) throw new Error(`expected 6236 ayahs, got ${total}`);

const body = lengths.map((s) => "  [" + s.join(",") + "],").join("\n");
const out = `// GENERATED by scripts/gen-ayah-lengths.mjs. Do not edit by hand; re-run the script.
// AYAH_LENGTHS[surah - 1][ayah - 1] = number of characters in that ayah's Arabic text (field arabic1, with diacritics).
// ${total} ayahs, 114 surahs. Numbers only: no Qur'an text is stored here.
export const AYAH_LENGTHS: number[][] = [
${body}
];
`;
fs.writeFileSync(path.resolve(here, "../app/data/ayahLengths.generated.ts"), out);
console.log(`wrote app/data/ayahLengths.generated.ts (${total} ayahs, ${(out.length / 1024).toFixed(1)} KiB)`);
