// Generates app/data/sajda.generated.ts: the verses of prostration as [surah, ayah] pairs, and nothing else (no text, no flags).
//
//   node scripts/gen-sajda.mjs           builds from the recorded response, tests/fixtures/alquran-sajda.json
//   node scripts/gen-sajda.mjs --live    fetches https://api.alquran.cloud/v1/sajda/quran-uthmani, saves it as that fixture, then builds
//
// Source: the same endpoint the legacy Sajda page uses. The service's `obligatory` / `recommended` flags are NOT carried over (they are a
// ruling that differs between traditions); the Arabic is not carried over either (the app shows the surah reader's text). The script
// FAILS (writes nothing) when the response is not 15 distinct real ayahs, so a changed upstream is noticed.
// Never hand-edit the generated file; re-run this script. tests/sajda.test.ts compares the generated pairs with the recorded response.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const FIXTURE = path.resolve(here, "../tests/fixtures/alquran-sajda.json");
const OUT = path.resolve(here, "../app/data/sajda.generated.ts");
const legacy = JSON.parse(fs.readFileSync(path.resolve(here, "../../app/assets/data/surah.json"), "utf8"));
const counts = legacy.map((s) => s.totalAyah);

if (process.argv.includes("--live")) {
  const res = await fetch(`${process.env.QURAN_API_BASE2 || "https://api.alquran.cloud/v1"}/sajda/quran-uthmani`);
  if (!res.ok) throw new Error(`sajda: HTTP ${res.status}`);
  fs.writeFileSync(FIXTURE, JSON.stringify(await res.json()));
}

const fail = (m) => {
  throw new Error(`sajda check failed: ${m}`);
};
const ayahs = JSON.parse(fs.readFileSync(FIXTURE, "utf8"))?.data?.ayahs;
if (!Array.isArray(ayahs) || ayahs.length !== 15) fail(`expected 15 ayahs, got ${Array.isArray(ayahs) ? ayahs.length : "none"}`);
const pairs = ayahs.map((a) => [a.surah?.number, a.numberInSurah]);
for (const [s, a] of pairs) {
  if (!Number.isInteger(s) || !Number.isInteger(a) || s < 1 || s > 114 || a < 1 || a > counts[s - 1]) fail(`${s}:${a} is not an ayah`);
}
const key = (p) => p[0] * 1000 + p[1];
for (let i = 1; i < pairs.length; i++) if (key(pairs[i]) <= key(pairs[i - 1])) fail("the list is not in Qur'an order without repeats");

const body = `// GENERATED by scripts/gen-sajda.mjs. Do not edit by hand; re-run the script.
// Source: api.alquran.cloud /v1/sajda/quran-uthmani (recorded in tests/fixtures/alquran-sajda.json). [surah, ayah] pairs only: no text, and
// none of the service's obligatory / recommended flags (a ruling that differs between traditions, which this app does not state).
export const SAJDA_AYAHS: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(pairs)};
`;
fs.writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${pairs.length} ayahs`);
