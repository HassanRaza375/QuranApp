// Writes app/data/audioSizes.generated.ts: the size in bytes of every full-surah audio file (114 surahs x 5 reciters), measured with a HEAD
// request through GitHub's redirect (so the four Git LFS files report the real audio size, not the 134-byte pointer). The Downloads
// feature uses it to show real sizes before a download starts and to refuse a file whose byte count differs.
//
//   node scripts/gen-audio-sizes.mjs            (about 3 minutes; needs a network; not part of the build or of CI)
//
// A 429 or 5xx is retried with a pause; the script stops without writing anything if any of the 570 sizes cannot be read.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const surahs = JSON.parse(fs.readFileSync(path.resolve(here, "../legacy/app/assets/data/surah.json"), "utf8"));
const reciters = JSON.parse(fs.readFileSync(path.resolve(here, "../legacy/app/assets/data/reciters.json"), "utf8"));
const ids = reciters.map((r) => String(r.id));

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function size(url) {
  for (let attempt = 1; attempt <= 6; attempt++) {
    try {
      const res = await fetch(url, { method: "HEAD", redirect: "follow", signal: AbortSignal.timeout(30000) });
      if (res.status === 429 || res.status >= 500) throw new Error(`HTTP ${res.status}`);
      const bytes = Number(res.headers.get("content-length"));
      if (res.status !== 200 || !Number.isInteger(bytes) || bytes < 10_000) throw new Error(`HTTP ${res.status}, ${bytes} bytes`);
      return bytes;
    } catch (e) {
      if (attempt === 6) throw new Error(`${url}: ${e.message}`, { cause: e });
      await sleep(1500 * attempt);
    }
  }
}

const table = Object.fromEntries(ids.map((id) => [id, new Array(surahs.length).fill(0)]));
const jobs = [];
for (const s of surahs) for (const id of ids) {
  const e = s.audio?.[id];
  if (!e?.url) throw new Error(`surah ${s.surahNo} has no audio url for reciter ${id}`);
  jobs.push({ surah: s.surahNo, id, url: e.url });
}
let next = 0;
await Promise.all(Array.from({ length: 6 }, async () => {
  while (next < jobs.length) {
    const j = jobs[next++];
    table[j.id][j.surah - 1] = await size(j.url);
  }
}));

const out = [
  "// GENERATED by scripts/gen-audio-sizes.mjs. Do not edit by hand; re-run the script.",
  "// Bytes of every full-surah audio file, from a HEAD request through the redirect: AUDIO_SIZES[reciterId][surah - 1] (reciter ids are the legacy",
  "// reciters.json ids). Measured " + new Date().toISOString().slice(0, 10) + ". The size sent with a download replaces these once it starts.",
  "export const AUDIO_SIZES: Record<string, readonly number[]> = {",
  ...ids.map((id) => `  "${id}": [${table[id].join(",")}],`),
  "};",
  "",
].join("\n");
fs.writeFileSync(path.resolve(here, "../app/data/audioSizes.generated.ts"), out);
console.log("wrote app/data/audioSizes.generated.ts:", jobs.length, "sizes; largest", Math.max(...ids.flatMap((id) => table[id])));
